package com.vanillahack.api.utils.other;

public final class ReplaceUtil {
    private ReplaceUtil() {}

    public static String replaceSymbols(String text) {
        if (text == null) return "";
        return text;
    }

    public static String protectedString(String text) {
        if (text == null) return "";
        return text;
    }
}
